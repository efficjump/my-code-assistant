export const APP_LOCALE_HINT_KEY = 'code-assistant.locale'

interface LocaleHintStorage {
  getItem: (key: string) => string | null
  setItem: (key: string, value: string) => void
}

const isAppLocale = (value: unknown): value is AppLocale => value === 'ko' || value === 'en'

export function resolveInitialAppLocale(storedHint: string | null | undefined): AppLocale {
  if (isAppLocale(storedHint)) return storedHint
  return DEFAULT_APP_LOCALE
}

export function readInitialAppLocale(storage?: LocaleHintStorage | null): AppLocale {
  let storedHint: string | null = null
  try {
    const resolvedStorage =
      storage === undefined ? (typeof window === 'undefined' ? null : window.localStorage) : storage
    storedHint = resolvedStorage?.getItem(APP_LOCALE_HINT_KEY) ?? null
  } catch {
    // Storage can be unavailable under a hardened or transient renderer origin.
  }
  return resolveInitialAppLocale(storedHint)
}

export function persistAppLocaleHint(locale: AppLocale, storage?: LocaleHintStorage | null): void {
  try {
    const resolvedStorage =
      storage === undefined ? (typeof window === 'undefined' ? null : window.localStorage) : storage
    resolvedStorage?.setItem(APP_LOCALE_HINT_KEY, locale)
  } catch {
    // Main-process settings remain authoritative when this non-sensitive hint cannot be stored.
  }
}

