const CATALOGS: Record<AppLocale, TranslationCatalog> = { ko, en }

const interpolate = (message: string, values: TranslationValues): string =>
  message.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, key: string) => {
    const value = values[key]
    return value === undefined ? placeholder : String(value)
  })

export interface I18n {
  locale: AppLocale
  localeTag: string
  t: (key: TranslationKey, values?: TranslationValues) => string
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string
  formatDateTime: (value: number | Date, options?: Intl.DateTimeFormatOptions) => string
}

export const createI18n = (locale: AppLocale): I18n => {
  const localeTag = LOCALE_TAGS[locale]
  return {
    locale,
    localeTag,
    t: (key, values = {}) => {
      const message = CATALOGS[locale][key]
      return typeof message === 'function' ? message(values) : interpolate(message, values)
    },
    formatNumber: (value, options) => new Intl.NumberFormat(localeTag, options).format(value),
    formatDateTime: (value, options) =>
      new Intl.DateTimeFormat(localeTag, options).format(
        value instanceof Date ? value : new Date(value),
      ),
  }
}

const I18nContext = createContext<I18n>(createI18n(DEFAULT_APP_LOCALE))

export function I18nProvider({ locale, children }: { locale: AppLocale; children: ReactNode }) {
  const value = useMemo(() => createI18n(locale), [locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = (): I18n => useContext(I18nContext)
